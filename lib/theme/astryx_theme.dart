/// Astryx semantic type roles, composed on the geometric scale.
///
/// Astryx names families per role and leaves loading to the app; its own
/// default is Figtree. This theme uses **Geograph** for every role.
///
/// Geograph ships one weight — Regular. That is a real constraint, not an
/// oversight: hierarchy here is carried by size, tracking and colour, and the
/// weight values are kept so the roles stay faithful to Astryx the moment a
/// weighted companion is bundled alongside it. Emphasis that relies on weight
/// alone (bold in message bodies, for instance) will not visually differ until
/// then. The display end of this ramp is set wide and tight-tracked the way
/// Material 3 Expressive wants it.
abstract final class AstryxText {
  static const String family = 'Geograph';

  /// Used for any glyph Geograph does not carry. It is a Latin typeface, and
  /// mail is not.
  static const List<String> fallback = <String>['Questrial'];

  static TextStyle _style(
    double size,
    FontWeight weight,
    Color color, {
    double tracking = 0,
  }) =>
      TextStyle(
        fontFamily: family,
        // A Latin face: anything outside it — a subject in Devanagari, a CJK
        // sender name — falls back rather than showing a blank box.
        fontFamilyFallback: fallback,
        fontSize: size,
        fontWeight: weight,
        color: color,
        letterSpacing: tracking,
        height: AstryxType.leading(size),
      );

  static TextStyle display1(Color c) =>
      _style(AstryxType.s7xl, AstryxType.semibold, c, tracking: -1.5);
  static TextStyle display2(Color c) =>
      _style(AstryxType.s6xl, AstryxType.semibold, c, tracking: -1.2);
  static TextStyle display3(Color c) =>
      _style(AstryxType.s5xl, AstryxType.semibold, c, tracking: -1.0);

  static TextStyle heading1(Color c) =>
      _style(AstryxType.s4xl, AstryxType.semibold, c, tracking: -0.7);
  static TextStyle heading2(Color c) =>
      _style(AstryxType.s3xl, AstryxType.semibold, c, tracking: -0.5);
  static TextStyle heading3(Color c) =>
      _style(AstryxType.s2xl, AstryxType.semibold, c, tracking: -0.3);
  static TextStyle heading4(Color c) =>
      _style(AstryxType.sXl, AstryxType.semibold, c, tracking: -0.2);

  static TextStyle body(Color c) =>
      _style(AstryxType.sBase, AstryxType.normal, c);
  static TextStyle bodyStrong(Color c) =>
      _style(AstryxType.sBase, AstryxType.medium, c);
  static TextStyle label(Color c) =>
      _style(AstryxType.sSm, AstryxType.medium, c, tracking: 0.3);
  static TextStyle supporting(Color c) =>
      _style(AstryxType.sSm, AstryxType.normal, c);
  static TextStyle caption(Color c) =>
      _style(AstryxType.sXs, AstryxType.medium, c, tracking: 0.7);
}

/// Milk & Orange, carried on a Material 3 **Expressive** tonal scheme.
///
/// The palette is generated by Material's own `expressive` variant from the
/// brand orange, then the roles that *are* the brand — primary, the surface
/// ramp, the outlines — are pinned back to the exact Milk & Orange values. The
/// result is Material's expressive tonal system with the app's own identity
/// intact, rather than an approximation of either.
ColorScheme buildAstryxScheme(
  Brightness brightness, {
  AceAccent accent = AceAccent.orange,
  /// The platform's own accent, when dynamic colouring is on. It is used as
  /// the seed and nothing else, so everything below — the contrast walk, the
  /// tinted surfaces, the readable inks — applies to it exactly as it does to
  /// a colour picked from the list.
  Color? dynamicSeed,
  /// True black for an OLED panel. Only meaningful in the dark theme.
  bool oled = false,
}) {
  final bool dark = brightness == Brightness.dark;

  // The base tones the accent is mixed into, before tinting.
  const Color milk = Color(0xFFFFFCF6);
  const Color milkDim = Color(0xFFF6EDE0);
  const Color milkDeep = Color(0xFFF0E6D6);
  const Color white = Color(0xFFFFFFFF);
  const Color ink = Color(0xFF1A1614);
  const Color inkDeep = Color(0xFF141110);
  const Color inkRaised = Color(0xFF201B17);
  const Color inkHigh = Color(0xFF2B2521);
  const Color inkHighest = Color(0xFF332C27);

  // Material's tonal palette desaturates the surface roles almost to grey, so
  // changing the accent changed the buttons and left the page looking
  // identical. Mixing a little of the accent into every surface is what makes
  // the theme read as global — and because the mix is small, the contrast
  // ratios barely move, which is what the contrast test checks.
  /// Walks an ink along its own lightness until it is readable on [surface].
  /// The page moved, so the ink has to move with it.
  Color readableOn(Color ink, Color surface, {double target = 4.5}) {
    Color candidate = ink;
    final Color toward = dark ? const Color(0xFFFFFFFF) : const Color(0xFF000000);
    for (int step = 0; step <= 20; step++) {
      if (contrastRatio(candidate, surface) >= target) return candidate;
      candidate = Color.lerp(candidate, toward, 0.06)!;
    }
    return candidate;
  }

  Color tinted(Color surface, double amount, [Color? fill]) => Color.lerp(
        surface,
        fill ?? readableAccent(accent.seed, dark: dark),
        amount,
      )!;

  // Moved along its own lightness until a label on it clears AA and the shape
  // itself reads against the page. The accent you pick is still the accent; it
  // is just made usable.
  final Color seed = dynamicSeed ?? accent.seed;
  Color primary = readableAccent(seed, dark: dark);

  // The page is tinted *with* the accent, so the accent has to be checked
  // against the page it actually sits on rather than the neutral one it was
  // measured against. A dark accent on a dark page that has been pulled towards
  // it stops reading as a shape; this walks it further until it does.
  for (int step = 0; step < 12; step++) {
    final Color page = tinted(dark ? ink : milk, dark ? 0.12 : 0.11, primary);
    final bool readsAsShape = contrastRatio(primary, page) >= 3.0;
    final bool carriesALabel =
        contrastRatio(primary, contrastingInk(primary)) >= 4.5;
    if (readsAsShape && carriesALabel) break;
    primary = Color.lerp(
      primary,
      dark ? const Color(0xFFFFFFFF) : const Color(0xFF000000),
      0.06,
    )!;
  }


  // Enough of the accent to actually read as a hue — a brown theme gets a beige
  // page, not a grey one with brown buttons. Small enough that the contrast
  // ratios barely move, which the contrast test then checks.
  final double tint = dark ? 0.12 : 0.11;
  final double tintStrong = dark ? 0.18 : 0.16;

  return ColorScheme.fromSeed(
    seedColor: seed,
    brightness: brightness,
    dynamicSchemeVariant: DynamicSchemeVariant.expressive,
    // Pinned, so the accent you chose is the accent you see: Material's tonal
    // mapping would otherwise shift it a step or two.
    primary: primary,
    // Computed, not hard-coded: an accent is the user's choice, so its contrast
    // cannot be assumed. This passes AA on all ten, in both modes.
    onPrimary: contrastingInk(primary),
    primaryContainer: dark ? const Color(0xFF503424) : const Color(0xFFFFE0C6),
    onPrimaryContainer:
        dark ? const Color(0xFFFFDCC2) : const Color(0xFF4A1B00),
    // Every surface is the accent-tinted Milk or Ink, so changing the accent
    // changes the page and not just the buttons. These were pinned constants,
    // which is exactly why the theme never felt global.
    surface: oled ? const Color(0xFF000000) : tinted(dark ? ink : milk, tint),
    surfaceContainerLowest: tinted(dark ? inkDeep : white, tint),
    surfaceContainerLow:
        oled ? const Color(0xFF070707) : tinted(dark ? inkRaised : milk, tint),
    surfaceContainer: tinted(dark ? inkRaised : milkDim, tint),
    surfaceContainerHigh:
        oled ? const Color(0xFF141414) : tinted(dark ? inkHigh : milkDim, tintStrong),
    surfaceContainerHighest: tinted(dark ? inkHighest : milkDeep, tintStrong),

    // The ink comes from the seed's own family, so a blue accent does not put
    // warm brown text on a blue page. Contrast is checked, not assumed.
    onSurface: readableOn(
      dark ? const Color(0xFFFAF3E8) : const Color(0xFF2A211B),
      tinted(dark ? ink : milk, tint),
      target: 7,
    ),
    onSurfaceVariant: readableOn(
      dark ? const Color(0xFFB7A99A) : const Color(0xFF6B5D50),
      // Measured against the muted surface, which is the darkest thing this
      // ink is ever put on — not the page, which is lighter.
      tinted(dark ? inkHighest : milkDeep, tintStrong),
    ),
    // Also the disabled-ink role, so it has to be readable: 5.1:1 on Milk,
    // where the previous value was 2.5:1.
    outline: dark ? const Color(0xFF9E8F80) : const Color(0xFF7A6A5A),
    // Material's expressive variant puts secondary and tertiary a long way from
    // the seed — with an orange accent, secondaryContainer came out *green*,
    // which is how the Close button ended up the wrong colour. They are the
    // accent at two strengths instead.
    secondaryContainer: tinted(dark ? inkRaised : milkDim, tintStrong),
    onSecondaryContainer:
        dark ? const Color(0xFFFFDCC2) : const Color(0xFF4A1B00),
    tertiaryContainer: tinted(dark ? inkRaised : milkDeep, tintStrong * 1.5),
    onTertiaryContainer:
        dark ? const Color(0xFFFFDCC2) : const Color(0xFF3A1500),
    outlineVariant: tinted(
      dark ? const Color(0xFF4A4038) : const Color(0xFFE0D2BE),
      tintStrong,
    ),
  );
}

/// Builds the app theme: the expressive scheme above, Astryx's type roles, and
/// component themes shaped the way expressive M3 shapes them — pills, large
/// continuous corners, tonal surfaces, and no shadows doing the work of
/// elevation.
ThemeData buildAstryxTheme(
  Brightness brightness, {
  AceAccent accent = AceAccent.orange,
  Color? dynamicSeed,
  bool oled = false,
}) {
  final ColorScheme scheme = buildAstryxScheme(
    brightness,
    accent: accent,
    dynamicSeed: dynamicSeed,
    oled: oled,
  );
  final AstryxColors c = AstryxColors.fromScheme(scheme);

  final TextTheme text = TextTheme(
    displayLarge: AstryxText.display1(c.textPrimary),
    displayMedium: AstryxText.display2(c.textPrimary),
    displaySmall: AstryxText.display3(c.textPrimary),
    headlineLarge: AstryxText.heading1(c.textPrimary),
    headlineMedium: AstryxText.heading2(c.textPrimary),
    headlineSmall: AstryxText.heading3(c.textPrimary),
    titleLarge: AstryxText.heading4(c.textPrimary),
    titleMedium: AstryxText.bodyStrong(c.textPrimary),
    bodyLarge: AstryxText.body(c.textPrimary),
    bodyMedium: AstryxText.body(c.textPrimary),
    bodySmall: AstryxText.supporting(c.textSecondary),
    labelLarge: AstryxText.label(c.textPrimary),
    labelMedium: AstryxText.supporting(c.textSecondary),
    labelSmall: AstryxText.caption(c.textSecondary),
  );

  const RoundedRectangleBorder sheetShape = RoundedRectangleBorder(
    borderRadius: BorderRadius.vertical(
      top: Radius.circular(AstryxRadius.sheet),
      bottom: Radius.circular(AstryxRadius.inner),
    ),
  );

  return ThemeData(
    useMaterial3: true,
    brightness: brightness,
    fontFamily: AstryxText.family,
    fontFamilyFallback: AstryxText.fallback,
    colorScheme: scheme,
    scaffoldBackgroundColor: c.backgroundBody,
    canvasColor: c.backgroundBody,
    dividerColor: c.border,
    splashFactory: InkSparkle.splashFactory,
    textTheme: text,
    extensions: <ThemeExtension<dynamic>>[c],
    pageTransitionsTheme: const PageTransitionsTheme(
      builders: <TargetPlatform, PageTransitionsBuilder>{
        // Modern Android gets the predictive-back transition; the rest get the
        // fade-forwards one, which is the closest to expressive motion.
        TargetPlatform.android: PredictiveBackPageTransitionsBuilder(),
        TargetPlatform.linux: FadeForwardsPageTransitionsBuilder(),
        TargetPlatform.windows: FadeForwardsPageTransitionsBuilder(),
        TargetPlatform.macOS: CupertinoPageTransitionsBuilder(),
        TargetPlatform.iOS: CupertinoPageTransitionsBuilder(),
      },
    ),
    appBarTheme: AppBarThemeData(
      backgroundColor: c.backgroundBody,
      foregroundColor: c.textPrimary,
      surfaceTintColor: Colors.transparent,
      elevation: 0,
      scrolledUnderElevation: 0,
      centerTitle: false,
      titleTextStyle: AstryxText.heading3(c.textPrimary),
      toolbarTextStyle: AstryxText.body(c.textPrimary),
    ),
    filledButtonTheme: FilledButtonThemeData(
      style: FilledButton.styleFrom(
        shape: const StadiumBorder(),
        textStyle: AstryxText.bodyStrong(c.onAccent),
      ),
    ),
    outlinedButtonTheme: OutlinedButtonThemeData(
      style: OutlinedButton.styleFrom(
        shape: const StadiumBorder(),
        textStyle: AstryxText.bodyStrong(c.textPrimary),
      ),
    ),
    textButtonTheme: TextButtonThemeData(
      style: TextButton.styleFrom(
        shape: const StadiumBorder(),
        textStyle: AstryxText.bodyStrong(c.textAccent),
      ),
    ),
    cardTheme: CardThemeData(
      color: c.backgroundCard,
      surfaceTintColor: Colors.transparent,
      elevation: 0,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.lg),
      ),
    ),
    bottomSheetTheme: BottomSheetThemeData(
      backgroundColor: c.backgroundSurface,
      surfaceTintColor: Colors.transparent,
      modalBackgroundColor: c.backgroundSurface,
      showDragHandle: true,
      shape: sheetShape,
    ),
    dialogTheme: DialogThemeData(
      backgroundColor: c.backgroundSurface,
      surfaceTintColor: Colors.transparent,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.sheet),
      ),
      titleTextStyle: AstryxText.heading3(c.textPrimary),
      contentTextStyle: AstryxText.body(c.textSecondary),
    ),
    inputDecorationTheme: InputDecorationTheme(
      filled: true,
      fillColor: c.backgroundMuted,
      contentPadding: const EdgeInsets.symmetric(
        horizontal: AstryxSpace.s4,
        vertical: AstryxSpace.s3,
      ),
      // Hint text is content, not a disabled control, so it takes the
      // readable secondary ink rather than the disabled one.
      hintStyle: AstryxText.body(c.textSecondary),
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.container),
        borderSide: BorderSide.none,
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.container),
        borderSide: BorderSide.none,
      ),
      focusedBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.container),
        borderSide: BorderSide(color: c.accent, width: 1.6),
      ),
      errorBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.container),
        borderSide: BorderSide(color: c.error),
      ),
      focusedErrorBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.container),
        borderSide: BorderSide(color: c.error, width: 1.6),
      ),
    ),
    // The updated Material 3 appearance, opted into once for the whole app:
    // the 2024 slider (stop indicator, gap either side of the handle) and the
    // 2024 progress indicator (track gap, rounded cap). Set here rather than on
    // each widget so there is one answer, and so a widget added later is the
    // same control as the rest.
    // The flag is deprecated because Flutter intends to flip the default; until
    // it does, asking for the 2024 appearance is the only way to get it. When
    // the default flips, this line and the ignore go.
    // ignore: deprecated_member_use
    sliderTheme: const SliderThemeData(year2023: false),
    chipTheme: ChipThemeData(
      shape: const StadiumBorder(),
      side: BorderSide.none,
      backgroundColor: c.backgroundMuted,
      selectedColor: c.accentMuted,
      labelStyle: AstryxText.label(c.textPrimary),
      secondaryLabelStyle: AstryxText.label(c.onAccentMuted),
      padding: const EdgeInsets.symmetric(
        horizontal: AstryxSpace.s3,
        vertical: AstryxSpace.s2,
      ),
    ),
    switchTheme: SwitchThemeData(
      thumbColor: WidgetStateProperty.resolveWith<Color?>(
        (Set<WidgetState> states) => states.contains(WidgetState.selected)
            ? c.onAccent
            : c.backgroundSurface,
      ),
      trackColor: WidgetStateProperty.resolveWith<Color?>(
        (Set<WidgetState> states) => states.contains(WidgetState.selected)
            ? c.accent
            : c.surfaceHighest,
      ),
      trackOutlineColor: WidgetStateProperty.resolveWith<Color?>(
        (Set<WidgetState> states) =>
            states.contains(WidgetState.selected) ? null : c.borderEmphasized,
      ),
    ),
    snackBarTheme: SnackBarThemeData(
      // The accent, so a message from the app looks like it came from the app
      // rather than from Android. The ink on it is the accent's own readable
      // ink, so the text is legible whatever accent is chosen.
      behavior: SnackBarBehavior.floating,
      backgroundColor: c.accent,
      contentTextStyle: AstryxText.body(c.onAccent),
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.element),
      ),
    ),
    listTileTheme: ListTileThemeData(
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.container),
      ),
      titleTextStyle: AstryxText.body(c.textPrimary),
      subtitleTextStyle: AstryxText.supporting(c.textSecondary),
      iconColor: c.iconSecondary,
    ),
    floatingActionButtonTheme: FloatingActionButtonThemeData(
      // The accent, matching AceFab — the compose button is the one action the
      // app is asking for, and a tint of the accent reads as disabled.
      backgroundColor: c.accent,
      foregroundColor: c.onAccent,
      elevation: 0,
      focusElevation: 0,
      hoverElevation: 0,
      highlightElevation: 0,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AstryxRadius.lg),
      ),
    ),
    progressIndicatorTheme: ProgressIndicatorThemeData(
      color: c.accent,
      linearTrackColor: c.surfaceHighest,
      circularTrackColor: Colors.transparent,
      // The 2024 indicator: a gap between the track and the cap, and a rounded
      // cap. Off by default until Flutter flips it, so it is asked for here —
      // and the flag is deprecated for the same reason.
      // ignore: deprecated_member_use
      year2023: false,
    ),
    dividerTheme: DividerThemeData(color: c.border, thickness: 1, space: 1),
    tooltipTheme: TooltipThemeData(
      decoration: BoxDecoration(
        color: c.inverseSurface,
        borderRadius: BorderRadius.circular(AstryxRadius.inner),
      ),
      textStyle: AstryxText.supporting(c.onInverseSurface),
    ),
  );
}
